pub fn table_merge(table: &str) -> Option<&'static TableMerge> {
    TABLE_MERGES.iter().find_map(|(name, rule)| (*name == table).then_some(rule))
}

pub(crate) fn is_rebuilt_column(table: &str, column: &str) -> bool {
    REBUILT_COLUMNS.contains(&(table, column))
}

pub(crate) fn position_column(table: &str) -> Option<&'static str> {
    match table_merge(table) {
        Some(TableMerge::Entity { position_column, .. }) => *position_column,
        _ => None,
    }
}
